import React from "react";
import { Audio, Composition, Series, interpolate, staticFile } from "remotion";
import {
  Ask,
  Bench,
  Halt,
  How,
  Intro,
  KnifeDemo,
  Learner,
  Outro,
  Problem,
  Stack,
  Sticky,
  WaterDemo,
  Why,
} from "./scenes";
import { FPS, sec } from "./ui";

const SCENES: [React.FC, number][] = [
  [Intro, 5],
  [Problem, 11],
  [How, 19],
  [KnifeDemo, 21],
  [WaterDemo, 13],
  [Why, 10],
  [Sticky, 12],
  [Halt, 18],
  [Ask, 9],
  [Learner, 22],
  [Bench, 18],
  [Stack, 10],
  [Outro, 8],
];

const TOTAL = SCENES.reduce((n, [, s]) => n + sec(s), 0);

// Background music (generated by scripts/make_music.py), faded out
// over the last 3 s so it ends with the outro.
const musicVolume = (f: number) =>
  0.55 * interpolate(f, [TOTAL - sec(3), TOTAL], [1, 0], {
    extrapolateLeft: "clamp",
    extrapolateRight: "clamp",
  });

const Video: React.FC = () => (
  <>
    <Audio src={staticFile("music.mp3")} volume={musicVolume} />
    <Series>
      {SCENES.map(([Scene, s], i) => (
        <Series.Sequence key={i} durationInFrames={sec(s)}>
          <Scene />
        </Series.Sequence>
      ))}
    </Series>
  </>
);

export const RemotionRoot: React.FC = () => (
  <Composition
    id="Sentinel"
    component={Video}
    durationInFrames={TOTAL}
    fps={FPS}
    width={1920}
    height={1080}
  />
);
